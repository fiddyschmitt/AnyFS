using System.Diagnostics.CodeAnalysis;
using System.Reflection;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.Json.Serialization;
using System.Text.Json.Serialization.Metadata;
using AnyFS.Sdk;

namespace AnyFS.Core.Settings;

/// <summary>One property of a settings POCO with its <see cref="SettingAttribute"/>.</summary>
public sealed record SettingProperty(PropertyInfo Property, SettingAttribute Attribute)
{
    public string Name => Property.Name;

    public string JsonName => JsonNamingPolicy.CamelCase.ConvertName(Property.Name);

    public bool IsSecret => Attribute.Secret;

    /// <summary>False when the attribute names platforms and this isn't one: the form leaves the field out; the JSON keeps the value.</summary>
    public bool IsForThisPlatform => Attribute.Platforms is not { Length: > 0 } platforms || platforms.Any(OperatingSystem.IsOSPlatform);
}

/// <summary>
/// Moves plugin settings between their POCO and the JSON stored in sources.json / collections.json.
/// Plugin types can't be source-generated by us, so this is the one place the reflection serializer is
/// used; the <c>[DynamicallyAccessedMembers]</c> annotation on <c>SettingsType</c> keeps built-in POCOs
/// intact under trimming, and third-party DLLs are never trimmed. Properties marked Secret never enter
/// the JSON: they're handed to the secret store and filled back in on load.
/// </summary>
public static class PluginSettingsBinder
{
    private const string Justification = "Plugin settings POCOs are reflected on purpose: their public properties are kept by the DynamicallyAccessedMembers annotation on ISourcePlugin.SettingsType / IMountProviderPlugin.SettingsType, and JsonSerializerIsReflectionEnabledByDefault is on in the app.";

    private static readonly JsonSerializerOptions Options = CreateOptions();

    [UnconditionalSuppressMessage("Trimming", "IL2026", Justification = Justification)]
    [UnconditionalSuppressMessage("AOT", "IL3050", Justification = Justification)]
    private static JsonSerializerOptions CreateOptions() => new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        PropertyNameCaseInsensitive = true,
        DefaultIgnoreCondition = JsonIgnoreCondition.WhenWritingNull,
        WriteIndented = true,
        Converters = { new JsonStringEnumConverter() },
        TypeInfoResolver = new DefaultJsonTypeInfoResolver(),
    };

    public static IReadOnlyList<SettingProperty> Describe([DynamicallyAccessedMembers(DynamicallyAccessedMemberTypes.PublicProperties)] Type settingsType)
    {
        var list = new List<SettingProperty>();
        foreach (var property in settingsType.GetProperties(BindingFlags.Public | BindingFlags.Instance))
        {
            if (!property.CanRead || !property.CanWrite)
            {
                continue;
            }

            var attribute = property.GetCustomAttribute<SettingAttribute>() ?? new SettingAttribute(property.Name);
            list.Add(new SettingProperty(property, attribute));
        }

        return list.OrderBy(p => p.Attribute.Order).ToList();
    }

    /// <summary>Builds the POCO from stored JSON (missing properties keep their defaults) and fills secrets back in.</summary>
    [UnconditionalSuppressMessage("Trimming", "IL2026", Justification = Justification)]
    [UnconditionalSuppressMessage("AOT", "IL3050", Justification = Justification)]
    public static object Materialise(
        [DynamicallyAccessedMembers(DynamicallyAccessedMemberTypes.PublicProperties | DynamicallyAccessedMemberTypes.PublicConstructors)] Type settingsType,
        JsonObject? json,
        Func<string, string?>? secretLookup = null)
    {
        object settings;
        if (json is null || json.Count == 0)
        {
            settings = Activator.CreateInstance(settingsType) ?? throw new InvalidOperationException($"could not create {settingsType.Name}");
        }
        else
        {
            settings = json.Deserialize(settingsType, Options) ?? throw new InvalidOperationException($"could not deserialise {settingsType.Name}");
        }

        if (secretLookup is not null)
        {
            foreach (var p in Describe(settingsType).Where(p => p.IsSecret && p.Property.PropertyType == typeof(string)))
            {
                var value = secretLookup(p.Name);
                if (value is not null)
                {
                    p.Property.SetValue(settings, value);
                }
            }
        }

        return settings;
    }

    /// <summary>JSON for the settings files, with secret properties removed and handed to <paramref name="secretSink"/>.</summary>
    [UnconditionalSuppressMessage("Trimming", "IL2026", Justification = Justification)]
    [UnconditionalSuppressMessage("AOT", "IL3050", Justification = Justification)]
    public static JsonObject Serialise(
        [DynamicallyAccessedMembers(DynamicallyAccessedMemberTypes.PublicProperties | DynamicallyAccessedMemberTypes.PublicConstructors)] Type settingsType,
        object settings,
        Action<string, string?>? secretSink = null)
    {
        var node = JsonSerializer.SerializeToNode(settings, settingsType, Options) as JsonObject ?? new JsonObject();
        foreach (var p in Describe(settingsType).Where(p => p.IsSecret))
        {
            node.Remove(p.JsonName);
            node.Remove(p.Name);
            if (secretSink is not null && p.Property.PropertyType == typeof(string))
            {
                secretSink(p.Name, p.Property.GetValue(settings) as string);
            }
        }

        return node;
    }

    /// <summary>A copy of the POCO with secrets blanked, for logging.</summary>
    public static JsonObject Scrubbed(
        [DynamicallyAccessedMembers(DynamicallyAccessedMemberTypes.PublicProperties | DynamicallyAccessedMemberTypes.PublicConstructors)] Type settingsType,
        object settings)
        => Serialise(settingsType, settings);
}
